def answer_with_confidence_check(image_path, question):
    answer1 = ask_question(image_path, question)
    answer2 = ask_question(image_path, question + " Please be specific.")
    if answer1.strip().lower()[:30] != answer2.strip().lower()[:30]:
        return f"CLARIFYING QUESTION NEEDED: Could you clarify what you mean by '{question}'?"
    else:
        return answer1

print(answer_with_confidence_check("astronaut.jpg", "What is happening in this image?"))

print(answer_with_confidence_check("hubble_deep_field.jpg", "What is the main object in this image?"))

from gtts import gTTS
from IPython.display import Audio

def speak_text(text, filename="output_audio.mp3"):
    tts = gTTS(text)
    tts.save(filename)
    return filename

caption = get_caption("astronaut.jpg")
audio_file = speak_text(caption)
Audio(audio_file)

import pandas as pd

results = []
for i, filename in enumerate(uploaded.keys()):
    caption = get_caption(filename)
    vqa_answer = answer_with_confidence_check(filename, "What is happening in this image?")
    audio_file = speak_text(caption, f"caption_{i}.mp3")

    results.append({
        "image": filename,
        "caption": caption,
        "vqa_answer": vqa_answer,
        "audio_file": audio_file
    })
    print(f"Image: {filename}\nCaption: {caption}\nVQA: {vqa_answer}\nAudio saved: {audio_file}\n---")

df = pd.DataFrame(results)
df.to_csv("results.csv", index=False)

