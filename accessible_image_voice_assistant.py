from PIL import Image

def get_caption(image_path):
    image = Image.open(image_path)
    prompt = "[INST] <image>\nDescribe this image in detail. [/INST]"
    inputs = processor(text=prompt, images=image, return_tensors="pt").to("cuda")
    output = model.generate(**inputs, max_new_tokens=100)
    return processor.decode(output[0], skip_special_tokens=True)

def ask_question(image_path, question):
    image = Image.open(image_path)
    prompt = f"[INST] <image>\n{question} [/INST]"
    inputs = processor(text=prompt, images=image, return_tensors="pt").to("cuda")
    output = model.generate(**inputs, max_new_tokens=50)
    return processor.decode(output[0], skip_special_tokens=True)

from PIL import Image

def get_caption(image_path):
    image = Image.open(image_path)
    messages = [{"role": "user", "content": [
        {"type": "image"},
        {"type": "text", "text": "Describe this image in detail."}
    ]}]
    text_prompt = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = processor(text=[text_prompt], images=[image], return_tensors="pt").to("cuda")
    output = model.generate(**inputs, max_new_tokens=100)
    result = processor.batch_decode(output, skip_special_tokens=True)[0]
    return result.split("assistant\n")[-1].strip()

def ask_question(image_path, question):
    image = Image.open(image_path)
    messages = [{"role": "user", "content": [
        {"type": "image"},
        {"type": "text", "text": question}
    ]}]
    text_prompt = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = processor(text=[text_prompt], images=[image], return_tensors="pt").to("cuda")
    output = model.generate(**inputs, max_new_tokens=50)
    result = processor.batch_decode(output, skip_special_tokens=True)[0]
    return result.split("assistant\n")[-1].strip()

